create table if not exists public.animals (
  id bigint generated by default as identity primary key,
  name text not null,
  species text not null check (species in ('Cachorro', 'Gato')),
  age text not null,
  size text not null,
  temperament text not null,
  status text not null default 'Disponível'
    check (status in ('Disponível', 'Em processo', 'Adotado')),
  story text not null,
  photo text not null,
  created_at timestamptz not null default now()
);

alter table public.animals enable row level security;

drop policy if exists "Anyone can view animals" on public.animals;
create policy "Anyone can view animals"
  on public.animals for select to anon
  using (true);

grant usage on schema public to anon;
grant select on public.animals to anon;

create table if not exists public.adoption_requests (
  id bigint generated by default as identity primary key,
  animal_id bigint references public.animals(id) on delete set null,
  animal_name text not null,
  applicant_name text not null,
  email text not null,
  phone text not null,
  message text not null default '',
  created_at timestamptz not null default now()
);

alter table public.adoption_requests enable row level security;

drop policy if exists "Visitors can submit adoption requests" on public.adoption_requests;
create policy "Visitors can submit adoption requests"
  on public.adoption_requests for insert to anon
  with check (
    char_length(applicant_name) between 2 and 100
    and char_length(email) between 5 and 160
    and char_length(phone) between 8 and 30
    and char_length(message) <= 600
  );

grant insert on public.adoption_requests to anon;
grant usage, select on all sequences in schema public to anon;
